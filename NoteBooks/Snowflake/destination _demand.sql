USE DATABASE ATMOSYNC;
USE SCHEMA STAGING;
SHOW TABLES;
SELECT COUNT(*) AS TOTAL_ROWS
FROM ATMOSYNC.STAGING.DESTINATION_DEMAND_CLEAN;
SELECT COUNT(*) AS TOTAL_ROWS
FROM ATMOSYNC.STAGING.IOT_CLEAN;

SELECT COUNT(*) AS TOTAL_ROWS
FROM ATMOSYNC.STAGING.ROUTES_CLEANED;

SELECT COUNT(*) AS TOTAL_ROWS
FROM ATMOSYNC.STAGING.VACCINE_SHIPMENTS_CLEANED;
DESCRIBE TABLE ATMOSYNC.STAGING.DESTINATION_DEMAND_CLEAN;
DESCRIBE TABLE ATMOSYNC.STAGING.IOT_CLEAN;

DESCRIBE TABLE ATMOSYNC.STAGING.ROUTES_CLEANED;

DESCRIBE TABLE ATMOSYNC.STAGING.VACCINE_SHIPMENTS_CLEANED;


SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(DESTINATION IS NULL) AS NULL_DESTINATION,
    COUNT_IF(DATE IS NULL) AS NULL_DATE,
    COUNT_IF(DEMAND IS NULL) AS NULL_DEMAND
FROM ATMOSYNC.STAGING.DESTINATION_DEMAND_CLEAN;