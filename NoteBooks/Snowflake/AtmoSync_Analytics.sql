-- ============================================================
-- AtmoSync - Analytics Layer
-- ============================================================

CREATE SCHEMA IF NOT EXISTS ATMOSYNC.ANALYTICS;


-- ============================================================
-- 1. SHIPMENT ANALYTICS
-- Vaccine shipment + route information
-- ============================================================

CREATE OR REPLACE TABLE ATMOSYNC.ANALYTICS.SHIPMENT_ANALYTICS AS
SELECT
    V.SHIPMENT_ID,
    V.CONTAINER_ID,
    V.VACCINE_TYPE,
    V.BATCH_ID,
    V.QUANTITY,
    V.SOURCE,
    V.DESTINATION,
    V.DEPARTURE_TIME,
    V.EXPECTED_ARRIVAL,
    V.MIN_TEMPERATURE,
    V.MAX_TEMPERATURE,
    R.ROUTE_ID,
    R.DISTANCE_KM,
    R.ESTIMATED_TRAVEL_TIME_HOURS
FROM ATMOSYNC.STAGING.VACCINE_SHIPMENTS_CLEANED V
LEFT JOIN ATMOSYNC.STAGING.ROUTES_CLEANED R
    ON REPLACE(V.SOURCE, '"', '') = R.SOURCE
   AND REPLACE(V.DESTINATION, '"', '') = R.DESTINATION;

SELECT *
FROM ATMOSYNC.ANALYTICS.SHIPMENT_ANALYTICS
LIMIT 10;


SELECT
    SHIPMENT_ID,
    SOURCE,
    DESTINATION,
    ROUTE_ID,
    DISTANCE_KM,
    ESTIMATED_TRAVEL_TIME_HOURS
FROM ATMOSYNC.ANALYTICS.SHIPMENT_ANALYTICS
LIMIT 10;

-- ============================================================
-- 2. IOT SENSOR ANALYTICS
-- Shipment-level temperature and sensor summary
-- ============================================================

CREATE OR REPLACE TABLE ATMOSYNC.ANALYTICS.IOT_SENSOR_ANALYTICS AS
SELECT
    SHIPMENT_ID,
    COUNT(*) AS SENSOR_READINGS,
    ROUND(AVG(TEMPERATURE), 2) AS AVG_TEMPERATURE,
    ROUND(MIN(TEMPERATURE), 2) AS MIN_TEMPERATURE,
    ROUND(MAX(TEMPERATURE), 2) AS MAX_TEMPERATURE,
    ROUND(AVG(HUMIDITY), 2) AS AVG_HUMIDITY,
    ROUND(AVG(VIBRATION), 2) AS AVG_VIBRATION,
    MIN(TIMESTAMP) AS FIRST_READING_TIME,
    MAX(TIMESTAMP) AS LAST_READING_TIME
FROM ATMOSYNC.STAGING.IOT_CLEAN
GROUP BY SHIPMENT_ID;


SELECT *
FROM ATMOSYNC.ANALYTICS.IOT_SENSOR_ANALYTICS
LIMIT 10;

-- ============================================================
-- 3. FINAL ATMO SYNC ANALYTICS
-- Shipment + Route + IoT + Destination Demand
-- ============================================================

CREATE OR REPLACE TABLE ATMOSYNC.ANALYTICS.ATMO_SYNC_ANALYTICS AS
SELECT
    S.SHIPMENT_ID,
    S.CONTAINER_ID,
    S.VACCINE_TYPE,
    S.BATCH_ID,
    S.QUANTITY,
    S.SOURCE,
    S.DESTINATION,

    S.ROUTE_ID,
    S.DISTANCE_KM,
    S.ESTIMATED_TRAVEL_TIME_HOURS,

    I.SENSOR_READINGS,
    I.AVG_TEMPERATURE,
    I.MIN_TEMPERATURE,
    I.MAX_TEMPERATURE,
    I.AVG_HUMIDITY,
    I.AVG_VIBRATION,
    I.FIRST_READING_TIME,
    I.LAST_READING_TIME,

    D.DEMAND,
    D.REQUIRED_QUANTITY,
    D.PRIORITY

FROM ATMOSYNC.ANALYTICS.SHIPMENT_ANALYTICS S

LEFT JOIN ATMOSYNC.ANALYTICS.IOT_SENSOR_ANALYTICS I
    ON REPLACE(S.SHIPMENT_ID, '"', '') = I.SHIPMENT_ID

LEFT JOIN ATMOSYNC.STAGING.DESTINATION_DEMAND_CLEAN_FIXED D
    ON S.DESTINATION = D.DESTINATION;


SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT SHIPMENT_ID) AS UNIQUE_SHIPMENTS,
    COUNT_IF(SHIPMENT_ID IS NULL) AS NULL_SHIPMENT_IDS,
    COUNT_IF(ROUTE_ID IS NULL) AS SHIPMENTS_WITHOUT_ROUTE,
    COUNT_IF(AVG_TEMPERATURE IS NULL) AS SHIPMENTS_WITHOUT_IOT_DATA,
    COUNT_IF(PRIORITY IS NULL) AS SHIPMENTS_WITHOUT_DEMAND_DATA
FROM ATMOSYNC.ANALYTICS.ATMO_SYNC_ANALYTICS;