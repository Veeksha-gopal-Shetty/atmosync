CREATE TABLE IF NOT EXISTS ATMOSYNC.STAGING.IOT_KAFKA_CLEAN (
    READING_ID VARCHAR,
    SHIPMENT_ID VARCHAR,
    CONTAINER_ID VARCHAR,
    TIMESTAMP TIMESTAMP_NTZ,
    TEMPERATURE FLOAT,
    HUMIDITY FLOAT,
    VIBRATION FLOAT,
    LATITUDE FLOAT,
    LONGITUDE FLOAT,
    TEMPERATURE_STATUS VARCHAR
);


--  Load Kafka RAW Data into Staging

INSERT INTO ATMOSYNC.STAGING.IOT_KAFKA_CLEAN
SELECT
    READING_ID::VARCHAR,
    SHIPMENT_ID::VARCHAR,
    CONTAINER_ID::VARCHAR,
    TIMESTAMP::TIMESTAMP_NTZ,
    TEMPERATURE::FLOAT,
    HUMIDITY::FLOAT,
    VIBRATION::FLOAT,
    LATITUDE::FLOAT,
    LONGITUDE::FLOAT,
    TEMPERATURE_STATUS::VARCHAR
FROM ATMOSYNC.RAW.IOT_KAFKA_RAW;


-- Caption: Create Shipment-Level Kafka IoT Analytics

CREATE OR REPLACE TABLE ATMOSYNC.ANALYTICS.IOT_KAFKA_ANALYTICS AS
SELECT
    SHIPMENT_ID,
    COUNT(*) AS SENSOR_READINGS,
    AVG(TEMPERATURE) AS AVG_TEMPERATURE,
    MIN(TEMPERATURE) AS MIN_TEMPERATURE,
    MAX(TEMPERATURE) AS MAX_TEMPERATURE,
    AVG(HUMIDITY) AS AVG_HUMIDITY,
    AVG(VIBRATION) AS AVG_VIBRATION,
    MIN(TIMESTAMP) AS FIRST_READING_TIME,
    MAX(TIMESTAMP) AS LAST_READING_TIME
FROM ATMOSYNC.STAGING.IOT_KAFKA_CLEAN
GROUP BY SHIPMENT_ID;


-- Create Final Kafka-Integrated Analytics

CREATE OR REPLACE TABLE ATMOSYNC.ANALYTICS.ATMO_SYNC_KAFKA_ANALYTICS AS
SELECT
    S.*,
    K.SENSOR_READINGS,
    K.AVG_TEMPERATURE AS KAFKA_AVG_TEMPERATURE,
    K.MIN_TEMPERATURE AS KAFKA_MIN_TEMPERATURE,
    K.MAX_TEMPERATURE AS KAFKA_MAX_TEMPERATURE,
    K.AVG_HUMIDITY AS KAFKA_AVG_HUMIDITY,
    K.AVG_VIBRATION AS KAFKA_AVG_VIBRATION,
    K.FIRST_READING_TIME AS KAFKA_FIRST_READING_TIME,
    K.LAST_READING_TIME AS KAFKA_LAST_READING_TIME
FROM ATMOSYNC.ANALYTICS.SHIPMENT_ANALYTICS S
JOIN ATMOSYNC.ANALYTICS.IOT_KAFKA_ANALYTICS K
    ON REPLACE(S.SHIPMENT_ID, '"', '') = K.SHIPMENT_ID;