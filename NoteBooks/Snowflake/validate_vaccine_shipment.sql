-- ATMOSYNC Vaccine Shipment Data Validation Scripts

-- 1. Row Count Check
SELECT 'RAW' AS STAGE, COUNT(*) AS TOTAL_ROWS FROM ATMOSYNC.RAW.VACCINE_SHIPMENTS_RAW
UNION ALL
SELECT 'STAGING' AS STAGE, COUNT(*) AS TOTAL_ROWS FROM ATMOSYNC.STAGING.VACCINE_SHIPMENTS_CLEANED;

-- 2. NULL Value Check
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(SHIPMENT_ID IS NULL) AS NULL_IDS,
    COUNT_IF(VACCINE_TYPE IS NULL) AS NULL_VACCINES,
    COUNT_IF(CONTAINER_ID IS NULL) AS NULL_CONTAINERS
FROM ATMOSYNC.STAGING.VACCINE_SHIPMENTS_CLEANED;

-- 3. Duplicate Check
SELECT
    SHIPMENT_ID,
    COUNT(*) AS DUPLICATE_COUNT
FROM ATMOSYNC.STAGING.VACCINE_SHIPMENTS_CLEANED
GROUP BY SHIPMENT_ID
HAVING COUNT(*) > 1;

-- 4. Find Removed Record
SELECT 
    RAW.SHIPMENT_ID
FROM ATMOSYNC.RAW.VACCINE_SHIPMENTS_RAW RAW
LEFT JOIN ATMOSYNC.STAGING.VACCINE_SHIPMENTS_CLEANED STG
    ON RAW.SHIPMENT_ID = STG.SHIPMENT_ID
WHERE STG.SHIPMENT_ID IS NULL;

-- 5. Range & Operational Boundary Check
SELECT
    MIN(MIN_TEMPERATURE) AS MIN_TEMP_RECORDED,
    MAX(MAX_TEMPERATURE) AS MAX_TEMP_RECORDED,
    MIN(QUANTITY) AS MIN_QUANTITY,
    MAX(QUANTITY) AS MAX_QUANTITY
FROM ATMOSYNC.STAGING.VACCINE_SHIPMENTS_CLEANED;

-- 6. Categorical Distribution Check
SELECT 
    VACCINE_TYPE, 
    COUNT(*) AS TOTAL_SHIPMENTS
FROM ATMOSYNC.STAGING.VACCINE_SHIPMENTS_CLEANED
GROUP BY VACCINE_TYPE
ORDER BY TOTAL_SHIPMENTS DESC;
