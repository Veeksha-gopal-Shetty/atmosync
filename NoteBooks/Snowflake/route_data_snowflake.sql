-- 1. Total rows
SELECT COUNT(*) AS TOTAL_ROUTES
FROM ATMOSYNC.RAW.ROUTES_RAW;

-- 2. Missing values
SELECT *
FROM ATMOSYNC.RAW.ROUTES_RAW
WHERE ROUTE_ID IS NULL
   OR SOURCE IS NULL
   OR DESTINATION IS NULL
   OR DISTANCE_KM IS NULL
   OR ESTIMATED_TRAVEL_TIME_HOURS IS NULL;

-- 3. Duplicate route IDs
SELECT ROUTE_ID, COUNT(*) AS COUNT
FROM ATMOSYNC.RAW.ROUTES_RAW
GROUP BY ROUTE_ID
HAVING COUNT(*) > 1;

-- 4. Invalid distance
SELECT *
FROM ATMOSYNC.RAW.ROUTES_RAW
WHERE DISTANCE_KM <= 0;

-- 5. Invalid travel time
SELECT *
FROM ATMOSYNC.RAW.ROUTES_RAW
WHERE ESTIMATED_TRAVEL_TIME_HOURS <= 0;